#!/usr/bin/env bash
# Regenerates config/base/crd/kustomization.yaml so it lists every CRD that
# controller-gen wrote to config/base/crd/bases. Run by `task manifests`, so
# adding a resource never requires editing the kustomization by hand.
set -euo pipefail

cd "$(dirname "$0")/../config/base/crd"

{
  echo "# Code generated by \`task manifests\`. DO NOT EDIT."
  echo "# Lists every CRD in bases/. Run \`task manifests\` after adding a resource."
  shopt -s nullglob
  crds=(bases/*.yaml)
  if [ ${#crds[@]} -eq 0 ]; then
    echo "resources: []"
  else
    echo "resources:"
    for crd in "${crds[@]}"; do
      echo "- ${crd}"
    done
  fi
} > kustomization.yaml
